"""Shared plumbing for the experiment scripts."""

from __future__ import annotations

import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
RESULTS = ROOT / "experiments" / "results"


class Report:
    """Accumulates markdown and writes it to ``experiments/results/``."""

    def __init__(self, slug: str, title: str, blurb: str = "") -> None:
        self.slug = slug
        self.lines: list[str] = [f"# {title}", ""]
        if blurb:
            self.lines += [blurb, ""]
        self.start = time.time()

    def p(self, text: str = "") -> None:
        self.lines.append(text)
        print(text, flush=True)

    def table(self, headers: list[str], rows: list[list]) -> None:
        self.p("| " + " | ".join(headers) + " |")
        self.p("|" + "|".join("---" for _ in headers) + "|")
        for row in rows:
            self.p("| " + " | ".join(str(c) for c in row) + " |")
        self.p()

    def write(self) -> Path:
        self.p(f"_Generated by `experiments/{self.slug}.py` "
               f"in {time.time() - self.start:.1f}s._")
        RESULTS.mkdir(parents=True, exist_ok=True)
        path = RESULTS / f"{self.slug}.md"
        path.write_text("\n".join(self.lines) + "\n")
        print(f"\n-> wrote {path.relative_to(ROOT)}", flush=True)
        return path
